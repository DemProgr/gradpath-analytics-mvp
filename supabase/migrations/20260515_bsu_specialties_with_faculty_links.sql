-- 3. Проверяем связи
SELECT 'Проверка связей специальностей БГУ:' as info;
SELECT f.name as faculty, COUNT(s.id) as specialty_count
FROM faculties f
LEFT JOIN specialties s ON s.faculty_id = f.id OR s.institute_id = f.id
WHERE f.university_id = 'bsu'
GROUP BY f.name
ORDER BY f.name;

-- 4. Проверяем что admission_stats соответствует специальностям
SELECT 'Проверка admission_stats для БГУ 2025:' as info;
SELECT 
  s.name as specialty,
  f.name as faculty,
  a.year,
  a.min_score,
  a.paid_min_score
FROM admission_stats a
JOIN specialties s ON s.id = a.specialty_id
LEFT JOIN faculties f ON f.id = s.faculty_id OR f.id = s.institute_id
WHERE a.specialty_id LIKE 'bsu-%' AND a.year = 2025
ORDER BY f.name, s.name
LIMIT 20;

-- 5. Итоговая статистика
SELECT 'Итоговая статистика:' as info;

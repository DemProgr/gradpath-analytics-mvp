  'Специальностей БГУ' as metric, COUNT(*) as value FROM specialties WHERE university_id = 'bsu'
UNION ALL
SELECT 'Факультетов БГУ', COUNT(*) FROM faculties WHERE university_id = 'bsu'
UNION ALL
